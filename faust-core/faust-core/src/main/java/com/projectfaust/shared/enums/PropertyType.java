/**
 * Type of real estate property in the cadaster.
 *
 * @author Dimitri / Project Faust
 */
public enum PropertyType {
    /** Land parcel (pozemek / parcela). */
    PARCEL,
    /** Standalone building (budova / stavba). */
    BUILDING,
    /** Residential or non-residential unit within a building (byt / nebytový prostor). */
    UNIT
}
